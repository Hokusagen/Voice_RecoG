"""Прилив голоса: три связанных пласта жидкости в канале пилюли.

Первая версия прилива складывала три независимые синусоиды — пласты не знали
друг о друге, и это читалось как готовый градиент из генератора. Здесь пласты
— струны, связанные между собой:

- верхний пласт — волновое уравнение с затуханием; голос толкает его в точке,
  которая медленно бродит по длине: каждый слог даёт импульс, волна бежит к
  торцам и отражается от них (свободные концы);
- каждый следующий пласт про голос не знает: он привязан пружиной к пласту над
  собой и несёт волну со своей, более медленной скоростью. Импульс уходит в
  глубину с запаздыванием и сглаживается — видно, как движение передаётся из
  слоя в слой.

Длина пилюли здесь — канал, по которому бежит волна: чем длиннее, тем дольше
импульс идёт до торца.

Единицы: x — доля длины канала 0…1, время — секунды, смещение — условное;
шейдер переводит его в долю высоты через tanh, так что крупный всплеск
мягко упирается, а не прошивает стекло.
"""

from __future__ import annotations

import math

import numpy as np

NODES = 48
LAYERS = 3

#: Скорость волны, длин канала в секунду: верхний быстрый, нижние догоняют.
SPEED = (0.95, 0.6, 0.4)
#: Затухание, 1/с: импульс проходит канал раз-другой и гаснет. Нижние пласты гасят
#: сильнее: связанные пружиной, они иначе раскачивались в резонанс и звенели в паузах.
DAMPING = (1.6, 2.4, 2.8)
#: Жёсткость связи с пластом выше, 1/с².
COUPLING = (0.0, 20.0, 14.0)
#: Возврат к уровню покоя, 1/с². Концы канала свободные, и у сдвига всего пласта
#: целиком нет возвращающей силы: толчки голоса всегда вверх, и без этой пружины
#: пласт уплывал, а в паузах не оседал.
RESTORE = (26.0, 8.0, 8.0)
#: Импульс слога: на нарастание огибающей слога и на ровное «помешивание» фразой.
ONSET_GAIN = 60.0
STIR_GAIN = 7.0


class Tide:
    def __init__(self) -> None:
        self.x = np.linspace(0.0, 1.0, NODES)
        self.dx = 1.0 / (NODES - 1)
        self.u = np.zeros((LAYERS, NODES))
        self.v = np.zeros((LAYERS, NODES))
        self.time = 0.0
        self.previous = 0.0

    def reset(self) -> None:
        self.u[:] = 0.0
        self.v[:] = 0.0
        self.previous = 0.0

    def step(self, dt: float, phrase: float, syllable: float) -> None:
        if dt <= 0.0:
            return
        self.time += dt
        t = self.time
        rise = max(0.0, syllable - self.previous) / dt
        self.previous = syllable
        # Точка, куда толкает голос, бродит медленно и непериодично.
        source = 0.5 + 0.32 * math.sin(0.41 * t) * math.cos(0.17 * t + 1.0)
        kernel = np.exp(-((self.x - source) / 0.09) ** 2)
        # Помешивание фразой — 1.4 Гц, в стороне от собственных частот нижних пластов (~0.8 Гц).
        drive = rise * ONSET_GAIN + phrase * STIR_GAIN * math.sin(2.0 * math.pi * 1.4 * t)
        force = kernel * drive

        # Явная схема устойчива при c·h/dx < 1: c 0.95, dx ≈ 0.021 — шаг не длиннее
        # ~0.02 с; три подшага на кадр с запасом.
        steps = max(1, math.ceil(dt / 0.006))
        h = dt / steps
        inv_dx2 = 1.0 / (self.dx * self.dx)
        for _ in range(steps):
            for k in range(LAYERS):
                u = self.u[k]
                # Свободные концы: производная по x на торцах ноль — волна отражается.
                padded = np.concatenate(([u[1]], u, [u[-2]]))
                laplacian = (padded[2:] - 2.0 * u + padded[:-2]) * inv_dx2
                accel = SPEED[k] ** 2 * laplacian - DAMPING[k] * self.v[k] - RESTORE[k] * u
                if k == 0:
                    accel = accel + force
                else:
                    accel = accel + COUPLING[k] * (self.u[k - 1] - u)
                self.v[k] += accel * h
                self.u[k] += self.v[k] * h

    def heights(self) -> np.ndarray:
        """Смещения всех пластов подряд: LAYERS·NODES чисел для шейдера."""
        return self.u.reshape(-1).astype(np.float32)

    def speeds(self) -> np.ndarray:
        return self.v.reshape(-1).astype(np.float32)
